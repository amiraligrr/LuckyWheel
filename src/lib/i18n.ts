const dictionaries: Record<Language, Record<TranslationKey, string>> = { fa, en };

export type Translate = (key: TranslationKey, vars?: Record<string, string | number>) => string;

export function createT(language: Language): Translate {
  const dictionary = dictionaries[language];
  return (key, vars) => {
    let value = dictionary[key] ?? fa[key] ?? key;
    if (vars) {
      for (const [name, replacement] of Object.entries(vars)) {
        value = value.split(`{${name}}`).join(String(replacement));
      }
    }
    return value;
  };
}

export function itemsCountLabel(language: Language, count: number): string {
  if (language === "fa") return `${count} گزینه`;
  return count === 1 ? "1 option" : `${count} options`;
}

export function settingsHistoryLabel(language: Language, count: number): string {
  if (language === "fa") return `${count} نتیجه ذخیره شده`;
  return count === 1 ? "1 saved result" : `${count} saved results`;
}
